def total_cost(fixed_cost, variable_cost):
    return fixed_cost + variable_cost 

def average_fixed_cost(fixed_cost, quantity):
    return fixed_cost / quantity 

def average_variable_cost(variable_cost, quantity):
    return variable_cost / quantity

def average_total_cost(total_cost_value, quantity):
    return total_cost_value / quantity

def marginal_cost(change_in_cost, change_in_quantity):
    return change_in_cost / change_in_quantity
